/* Writes every translation the archive holds into scripts/translations.json,
   keyed by slug, so import-real.mjs can restore them on a fresh project.

   Found the hard way: the Hebrew and Russian names, the French, German and
   Spanish communities, the yeshivot in Cyrillic — all of it was written
   straight into the first database and lived nowhere else. Standing up the
   client's project reproduced the schema and the roster perfectly and lost
   every translation. Run this after any translation work in the back office;
   commit the result. */

import { readFileSync, writeFileSync } from 'node:fs';

for (const l of readFileSync('.env.supabase', 'utf8').split('\n')) {
  const m = l.match(/^([A-Z_][A-Z0-9_]*)=(.*)$/);
  if (m && !process.env[m[1]]) process.env[m[1]] = m[2].trim();
}
const U = process.env.SUPABASE_URL, K = process.env.SUPABASE_SERVICE_ROLE_KEY;
const q = async p => (await fetch(`${U}/rest/v1${p}`,
  { headers: { apikey: K, Authorization: `Bearer ${K}` } })).json();

const bySlug = (rows, tr, cols) => Object.fromEntries(
  rows.filter(r => r.slug).sort((a, b) => a.slug.localeCompare(b.slug)).map(r => [
    r.slug,
    Object.fromEntries((r[tr] || []).sort((a, b) => a.lang.localeCompare(b.lang)).map(t => [
      t.lang,
      cols.length === 1 ? t[cols[0]] : Object.fromEntries(cols.filter(c => t[c] != null).map(c => [c, t[c]]))
    ]))
  ]));

const out = {
  _note: 'Generated by scripts/export-translations.mjs. Keyed by slug; applied by import-real.mjs. Edit in the back office, then re-export — do not hand-edit.',
  _exported: new Date().toISOString().slice(0, 10),
  communities:  bySlug(await q('/tmz_community?select=slug,tmz_community_tr(lang,name,country,blurb)&limit=1000'),
                       'tmz_community_tr', ['name', 'country', 'blurb']),
  institutions: bySlug(await q('/tmz_institution?select=slug,tmz_institution_tr(lang,name)&limit=1000'),
                       'tmz_institution_tr', ['name']),
  people:       bySlug(await q('/tmz_person?select=slug,tmz_person_tr(lang,display_name)&limit=2000'),
                       'tmz_person_tr', ['display_name'])
};

writeFileSync('scripts/translations.json', JSON.stringify(out, null, 1) + '\n');
const n = o => Object.values(o).reduce((s, v) => s + Object.keys(v).length, 0);
console.log(`translations.json: ${n(out.communities)} community, ${n(out.institutions)} institution, ${n(out.people)} person rows`);
